#!/usr/bin/env python3
"""Misfit Mercenaries — media index builder.

Runs in the GitHub Action before every deploy (see .github/workflows/site.yml).
For each album in site/data/albums.json it scans site/media/<album id>/ for:
  - screenshots: .jpg .jpeg .png .webp .gif   (a file named cover.* becomes the album cover)
  - video files: .mp4 .webm                   (GitHub web upload limit is 25 MB per file)
  - videos.txt:  one link per line, optional "| title"; YouTube links become playable videos
It makes small preview images in site/media/<album>/thumbs/ (not committed) and writes
site/data/media.json, which the Media page reads.

Needs Pillow for thumbnails (pip install pillow). Without it, full images are used as previews.
Run locally with:  python3 scripts/build-media.py
"""
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
MEDIA = SITE / "media"
IMG_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif"}
VID_EXT = {".mp4", ".webm"}
THUMB_W = 640

try:
    from PIL import Image, ImageOps
except ImportError:  # still works, just without thumbnails
    Image = None
    print("[media] Pillow not installed: using full images as previews", file=sys.stderr)


def youtube_id(url):
    m = re.search(r"(?:youtu\.be/|v=|/shorts/|/embed/|/live/)([A-Za-z0-9_-]{11})", url)
    return m.group(1) if m else None


def make_thumb(src, album_dir):
    rel = src.relative_to(SITE).as_posix()
    if Image is None:
        return rel, None, None
    # thumbnail name includes a short content hash, so a replaced image gets a fresh thumbnail
    digest = hashlib.sha1(src.read_bytes()).hexdigest()[:8]
    out = album_dir / "thumbs" / f"{src.stem}-{digest}.webp"
    try:
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im)
            w, h = im.size
            if not out.exists():
                out.parent.mkdir(exist_ok=True)
                t = im.convert("RGB")
                if t.width > THUMB_W:
                    t = t.resize((THUMB_W, round(t.height * THUMB_W / t.width)), Image.LANCZOS)
                t.save(out, "WEBP", quality=80, method=6)
            return out.relative_to(SITE).as_posix(), w, h
    except Exception as e:  # unreadable image: show the original
        print(f"[media] could not read {rel}: {e}", file=sys.stderr)
        return rel, None, None


def make_poster(src, album_dir):
    """Grab a frame ~1 s into a video file as its preview image (needs ffmpeg; skipped if missing)."""
    if not shutil.which("ffmpeg"):
        return None
    digest = hashlib.sha1(src.read_bytes()).hexdigest()[:8]
    out = album_dir / "thumbs" / f"{src.stem}-{digest}.jpg"
    if not out.exists():
        out.parent.mkdir(exist_ok=True)
        r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-ss", "1", "-i", str(src), "-frames:v", "1",
                            "-vf", f"scale={THUMB_W}:-2", "-q:v", "4", str(out)], capture_output=True)
        if r.returncode != 0 or not out.exists():
            return None
    return out.relative_to(SITE).as_posix()


def nice_title(stem):
    """Readable caption from a file name; generic names like clip-03 get no caption."""
    m = re.fullmatch(r"(.*?)[_ -]+(\d{4})[_ -](\d{2})[_ -](\d{2}).*", stem)
    if m:  # e.g. reforger-2025-03-03 -> "Reforger · 2025-03-03"
        name = re.sub(r"[_-]+", " ", m.group(1)).strip()
        return (name[:1].upper() + name[1:] + " · " if name else "") + f"{m.group(2)}-{m.group(3)}-{m.group(4)}"
    t = re.sub(r"[_-]+", " ", stem).strip()
    if re.fullmatch(r"(clip|video|vid)\s*\d+", t, re.I):
        return ""
    return t[:1].upper() + t[1:]


def main():
    cfg = json.loads((SITE / "data" / "albums.json").read_text(encoding="utf-8"))
    out = {"_comment": "Generated by scripts/build-media.py on every deploy. Do not edit by hand.", "albums": []}
    total = 0
    for a in cfg["albums"]:
        d = MEDIA / a["id"]
        items, clips, cover = [], [], None
        if d.is_dir():
            # natural file-name order: 2 before 10, and date-named files oldest first
            natural = lambda f: [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", f.name.lower())]
            files = sorted((f for f in d.iterdir() if f.is_file()), key=natural)
            for f in files:
                ext = f.suffix.lower()
                if ext in IMG_EXT:
                    thumb, w, h = make_thumb(f, d)
                    item = {"type": "image", "src": f.relative_to(SITE).as_posix(), "thumb": thumb, "w": w, "h": h,
                            "title": re.sub(r"[_-]+", " ", f.stem).strip()}
                    if f.stem.lower() == "cover":
                        cover = item
                    else:
                        items.append(item)
                elif ext in VID_EXT:
                    clips.append({"type": "video", "src": f.relative_to(SITE).as_posix(),
                                  "poster": make_poster(f, d), "title": nice_title(f.stem)})
            links = d / "videos.txt"
            if links.exists():
                vids = []
                for line in links.read_text(encoding="utf-8").splitlines():
                    line = line.strip()
                    if not line or line.startswith("#"):
                        continue
                    url, _, title = (p.strip() for p in line.partition("|"))
                    yid = youtube_id(url)
                    vids.append({"type": "youtube", "id": yid, "url": url, "title": title} if yid
                                else {"type": "link", "url": url, "title": title or url})
                items = vids + clips + items  # videos first, then screenshots
        if clips and not any(i["type"] == "video" for i in items):
            items = clips + items
        if cover is None and a.get("cover"):
            cover = next((i for i in items if i["type"] == "image" and i["src"].endswith("/" + a["cover"])), None)
        if cover is None:
            cover = next((i for i in items if i["type"] == "image"), None)
        if cover is None:
            yt = next((i for i in items if i["type"] == "youtube"), None)
            if yt:
                cover = {"type": "image", "thumb": f"https://i.ytimg.com/vi/{yt['id']}/hqdefault.jpg"}
        total += len(items)
        out["albums"].append({**{k: a[k] for k in ("id", "name", "era", "group", "active")},
                              "cover": cover["thumb"] if cover else None, "count": len(items), "items": items})
    (SITE / "data" / "media.json").write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")
    print(f"[media] {len(out['albums'])} albums, {total} items")


if __name__ == "__main__":
    main()
